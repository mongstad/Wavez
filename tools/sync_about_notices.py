"""Generate the exportable About resource from canonical repository notices."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "viewer/ui/about/notices.tres"
SOURCES = {
    "WAVEZ — PolyForm Noncommercial 1.0.0": "LICENSE",
    "Third-party inventory": "THIRD_PARTY_LICENSES.md",
    "Branding": "TRADEMARKS.md",
    "Godot runtime — MIT License (canonical)": "GODOT_LICENSE.txt",
    "Godot component notices (canonical)": "GODOT_COPYRIGHT.txt",
    "Colormap notices": "viewer/COLORMAPS_LICENSE.txt",
    "DejaVu font notices": "viewer/ui/fonts/LICENSE-DejaVu.txt",
}


def resource_text(root=ROOT) -> str:
    texts = {title: (root / path).read_text(encoding="utf-8") for title, path in SOURCES.items()}
    notice = next(line.removeprefix("Required Notice: ") for line in texts[next(iter(SOURCES))].splitlines()
                  if line.startswith("Required Notice: Copyright"))
    return ('; Generated by tools/sync_about_notices.py; edit the canonical source documents.\n'
            '[gd_resource type="Resource" format=3]\n\n[resource]\n'
            'metadata/copyright = ' + json.dumps(notice, ensure_ascii=False) + '\n'
            'metadata/notices = ' + json.dumps(texts, ensure_ascii=False, indent=2) + '\n')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if packaged notices differ from their sources")
    args = parser.parse_args()
    expected = resource_text()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            parser.exit(1, "Packaged About notices are stale; run python tools/sync_about_notices.py\n")
    else:
        OUTPUT.write_text(expected, encoding="utf-8")


if __name__ == "__main__":
    main()
